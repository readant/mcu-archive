/*------------------------------------------------
  功能：蜂鸣器基本发声
  硬件：有源蜂鸣器接P1.5
  说明：有源蜂鸣器只需给高低电平即可发声
------------------------------------------------*/
#include <reg51.h>

sbit BEEP = P1^5;

void Delay(unsigned int t)
{
    while (--t);
}

void main(void)
{
    while (1)
    {
        BEEP = 0;       // 响
        Delay(50000);
        BEEP = 1;       // 停
        Delay(50000);
    }
}
