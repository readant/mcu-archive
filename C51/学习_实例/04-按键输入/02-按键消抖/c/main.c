/*------------------------------------------------
  功能：按键消抖（软件延时消抖）
  硬件：P2.0接按键，P0.0接LED
  说明：演示标准的按键消抖流程
        检测按下 → 延时20ms → 再次确认 → 等待松手
------------------------------------------------*/
#include <reg51.h>

sbit KEY = P2^0;
sbit LED = P0^0;

void Delay(unsigned int t)
{
    while (--t);
}

void main(void)
{
    LED = 1;  // 初始熄灭

    while (1)
    {
        if (KEY == 0)               // 1. 检测到按键按下
        {
            Delay(20);              // 2. 延时20ms消抖
            if (KEY == 0)           // 3. 再次确认
            {
                LED = !LED;         // 4. 执行动作
                while (!KEY);       // 5. 等待按键松开
            }
        }
    }
}
