/*------------------------------------------------
  功能：C51数据类型演示
  硬件：P0口接LED
  说明：展示C51中常用的数据类型
------------------------------------------------*/
#include <reg51.h>

void Delay(unsigned int t)
{
    while (--t);
}

void main(void)
{
    /*--- 基本数据类型 ---*/
    bit flag = 0;           // 位变量，只能0或1
    unsigned char a = 255;  // 无符号字符，0~255
    signed char b = -128;   // 有符号字符，-128~127
    unsigned int c = 65535; // 无符号整型，0~65535
    signed int d = -32768;  // 有符号整型

    /*--- 特殊数据类型 ---*/
    unsigned long e = 12345678;  // 无符号长整型
    float f = 3.14;              // 浮点型（慎用，占资源多）

    /*--- 位操作 ---*/
    flag = 1;
    if (flag)
    {
        P0 = 0x00;  // LED全亮
    }

    /*--- 数据范围测试 ---*/
    a = 256;    // 溢出！a会变成0
    c = 70000;  // 溢出！c会变成某个值

    /*--- sizeof运算符 ---*/
    // a = sizeof(char);   // a = 1
    // c = sizeof(int);    // c = 2

    while (1);
}
