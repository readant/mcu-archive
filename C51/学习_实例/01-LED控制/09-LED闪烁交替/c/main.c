/*------------------------------------------------
  功能：LED交替闪烁（奇偶位）
  硬件：P0口接8个LED，低电平点亮
  说明：奇数位和偶数位交替闪烁
------------------------------------------------*/
#include <reg51.h>

void Delay(unsigned int t)
{
    while (--t);
}

void main(void)
{
    while (1)
    {
        P0 = 0xAA;     // 1010 1010，偶数位亮
        Delay(50000);
        P0 = 0x55;     // 0101 0101，奇数位亮
        Delay(50000);

        P0 = 0xCC;     // 1100 1100，高2低2交替
        Delay(50000);
        P0 = 0x33;     // 0011 0011
        Delay(50000);

        P0 = 0x0F;     // 高4位灭，低4位亮
        Delay(50000);
        P0 = 0xF0;     // 高4位亮，低4位灭
        Delay(50000);
    }
}
