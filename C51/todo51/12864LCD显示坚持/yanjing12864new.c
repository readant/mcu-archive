/* ========== 驱动函数 ========== */
void delay(uint k) {
    uint i;
    for (; k > 0; k--)
        for (i = 0; i < 124; i++);
}

void lcd_busy(void) {
    p_di = 0;
    p_rw = 1;
}

void wcode(uchar c, uchar csl, uchar csr) {
    p_csl = csl;
    p_csr = csr;
    lcd_busy();
    p_di = 0;
    p_rw = 0;
    lcm = c;
    p_e = 1;
    p_e = 0;
}

void wdata(uchar c, uchar csl, uchar csr) {
    p_csl = csl;
    p_csr = csr;
    lcd_busy();
    p_di = 1;
    p_rw = 0;
    lcm = c;
    p_e = 1;
    p_e = 0;
}

void set_startline(uchar i) {
    i = 0xc0 + i;
    wcode(i, 1, 1);
}

void set_xy(uchar x, uchar y) {
    x = x + 0x40;
    y = y + 0xb8;
    wcode(x, 1, 1);
    wcode(y, 1, 1);
}

void dison_off(uchar o) {
    o = o + 0x3e;
    wcode(o, 1, 1);
}

void reset(void) {
    p_rst = 0;
    delay(20);
    p_rst = 1;
    delay(20);
}

void lcd_init(void) {
    uchar x, y;
    reset();
    dison_off(0);
    for (y = 0; y < 8; y++)
        for (x = 0; x < 128; x++)
            lw(x, y, 0);
    dison_off(1);
    set_startline(0);
}

void lw(uchar x, uchar y, uchar dd) {
    if (x >= 64) {
        set_xy(x - 64, y);
        wdata(dd, 0, 1);
    } else {
        set_xy(x, y);
        wdata(dd, 1, 0);
    }
}

void disp_Hz(uchar xx, uchar yy, uchar n, uchar fb) {
    uchar i, dx;
    for (i = 0; i < 16; i++) {
        dx = HZ[2 * i + n * 32];
        if (fb) dx = 255 - dx;
        lw(xx * 16 + i, yy, dx);
        dx = HZ[2 * i + 1 + n * 32];
        if (fb) dx = 255 - dx;
        lw(xx * 16 + i, yy + 1, dx);
    }
}

void disp_Ez(uchar xx, uchar yy, uchar n, uchar fb) {
    uchar i, dx;
    for (i = 0; i < 8; i++) {
        dx = Ez[2 * i + n * 16];
        if (fb) dx = 255 - dx;
        lw(xx * 8 + i, yy, dx);
        dx = Ez[2 * i + 1 + n * 16];
        if (fb) dx = 255 - dx;
        lw(xx * 8 + i, yy + 1, dx);
    }
}

